Instructions d'installation et de lancement local







Décompresser l'archive :



unzip thermal-datacenter-tcu.zip -d thermal-datacenter-tcu
cd thermal-datacenter-tcu








Installer les dépendances :
Avec bun (recommandé) ou npm :



bun install
# ou : npm install








Lancer le serveur de développement :



bun dev
# ou : npm run dev
